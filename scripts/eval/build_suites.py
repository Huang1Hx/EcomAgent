def agent_rows() -> list[dict]:
    rows = []
    used = set()

    def add(extra: dict) -> None:
        if "query" in extra:
            assert extra["query"] not in used, f"Agent 问句重复:{extra['query']}"
            used.add(extra["query"])
        rows.append(_common(f"AGT-{len(rows) + 1:03d}", "agent", "test",
                            "ai_assisted_template", extra))

    for text, intents, tools, actions in AGENT_SINGLE:
        add({"query": text, "expect_intent_any": intents, "tools_required": tools,
             "actions_required": actions, "checks": ["answer_nonempty"], "kind": "single"})
    for text, tools, actions, scope in AGENT_TOOLCHAIN:
        add({"query": text, "tools_required": tools, "tools_in_order": True,
             "actions_required": actions, "order_scope": scope,
             "checks": ["tools", "tool_order", "tool_result", "answer_nonempty",
                        "actions", "order_scope"], "kind": "toolchain"})
    for turns, checks in AGENT_MULTI:
        add({"turns": turns, "checks": checks, "kind": "multi"})
    return rows


