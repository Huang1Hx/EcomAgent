def _text_key(rows: list[dict]) -> str | None:
    task = rows[0]["task"]
    return {"flywheel": "raw_question", "context": None, "agent": "query"}.get(task, "query")


def dedup(rows: list[dict], field: str = "query") -> list[str]:
    seen = Counter(r.get(field, "") for r in rows)
    return [t for t, c in seen.items() if c > 1 and t]


def _support(rows: list[dict]) -> dict:
    support = {}
    for key in ("bucket", "expect_intent", "kind"):
        c = Counter(str(r[key]) for r in rows if r.get(key) is not None)
        if c:
            support[key] = dict(sorted(c.items()))
    support["review_status"] = dict(sorted(Counter(r["review_status"] for r in rows).items()))
    return support


def manifest(path: Path, rows: list[dict], *, task: str, split: str, source: str) -> dict:
    key = _text_key(rows)
    duplicated = dedup(rows, key) if key else []
    return {
        "dataset": str(path.relative_to(ROOT)),
        "task": task, "split": split, "source": source,
        "generation_method": GEN_METHOD, "review_status": REVIEW, "reviewers": 0,
        "generated_at": TODAY,
        "samples": len(rows), "support": _support(rows),
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "dedup": {"text_field": key, "duplicate_texts": duplicated,
                  "exact_text_unique": not duplicated},
        "independent_release_evidence": False,
        "note": ("AI 辅助编写、未经真实人工审核;只能用于开发/回归,不得表述为人工审核或"
                 "已验证的独立发布证据。人工审核后须更新 review_status/reviewers 并重算哈希。"),
    }


def write(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows),
                    encoding="utf-8")


def main() -> int:
    legacy = [json.loads(l) for l in LEGACY.read_text(encoding="utf-8").splitlines() if l.strip()]
    dev = _legacy_rows()
    assert len(dev) == 300 and len(legacy) == 300
    blind = rag_rows()
    assert not (all_rag_queries() & {r["query"] for r in dev}), "新题不得与旧开发集逐字重复"
    writes = {
        "rag_dev.jsonl": (dev, "rag", "dev", "legacy300"),
        "rag_blind_test.jsonl": (blind, "rag", "test", "kb"),
        "intent_test.jsonl": (intent_rows(), "intent", "test", "ai_assisted_template"),
        "agent_test.jsonl": (agent_rows(), "agent", "test", "ai_assisted_template"),
        "flywheel_closure_test.jsonl": (flywheel_rows(), "flywheel", "test", "ai_assisted_gap"),
        "context_test.jsonl": (context_rows(), "context", "test", "ai_assisted_multi_turn"),
        "confidence_calibration.jsonl": (confidence_rows("calibration"), "confidence",
                                         "calibration", "kb"),
        "confidence_blind_test.jsonl": (confidence_rows("blind"), "confidence", "blind", "kb"),
    }
    for name, (rows, task, split, source) in writes.items():
        path = OUT / name
        write(path, rows)
        m = manifest(path, rows, task=task, split=split, source=source)
        if name == "rag_dev.jsonl":
            m["legacy_development_set"] = {
                "path": str(LEGACY.relative_to(ROOT)), "samples": len(legacy),
                "sha256": hashlib.sha256(LEGACY.read_bytes()).hexdigest(),
                "usage": "development_only", "not_independent_test": True,
            }
        mpath = OUT / "manifests" / f"{path.stem}.json"
        mpath.parent.mkdir(parents=True, exist_ok=True)
        mpath.write_text(json.dumps(m, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"{name}: {len(rows)} 条 -> {mpath.relative_to(ROOT)}")

    # 生成器自检:数据合同的核心约束在这里先失败,不让坏数据落盘到发布评测
    cal = {r["query"] for r in writes["confidence_calibration.jsonl"][0]}
    cblind = [r for r in writes["confidence_blind_test.jsonl"][0] if r["should_refuse"]]
    assert not (cal & {r["query"] for r in writes["confidence_blind_test.jsonl"][0]})
    assert len(cblind) >= 120
    assert Counter(r["bucket"] for r in blind)["D_absent"] >= 60
    intent = writes["intent_test.jsonl"][0]
    support = Counter(r["expect_intent"] for r in intent if r.get("expect_intent"))
    assert set(support) == set(INTENT_CLASSES) and min(support.values()) >= 20, support
    assert sum(r["kind"] in ("drift", "boundary") for r in intent) >= 45
    kinds = Counter(r["kind"] for r in writes["agent_test.jsonl"][0])
    assert kinds["single"] >= 90 and kinds["toolchain"] >= 15 and kinds["multi"] >= 15, kinds
    return 0


