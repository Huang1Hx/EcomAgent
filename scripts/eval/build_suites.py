def _date(i: int) -> str:
    """分散到 2026-09-01 ~ 2026-10-16,避免同一时间戳被当成同批生成。"""
    month = 9 if i < 16 else 10
    day = (i % 16) + 1
    return f"2026-{month:02d}-{day:02d}"


