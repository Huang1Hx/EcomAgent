def _turn_text(turn: str) -> str:
    return turn.split(":", 1)[1] if ":" in turn else turn


def intent_rows() -> list[dict]:
    rows = []
    used = set()
    for label, qs in INTENT_TEMPLATES.items():
        variants = qs + [qs[j % len(qs)] + tail for j, tail in enumerate(INTENT_TAILS)]
        assert len(variants) >= 20, (label, len(variants))
        for query in variants:
            assert query not in used, f"意图模板重复:{query}"
            used.add(query)
            rows.append(_common(f"INT-{INTENT_CODES[label]}-{len(rows) + 1:03d}", "intent",
                                "test", "ai_assisted_template",
                                {"query": query, "expect_intent": label, "kind": "single"}))
    drift = 0
    for turns, expect in DRIFT_CASES:
        query = _turn_text(turns[-1])
        assert query not in used, f"漂移问句重复:{query}"
        used.add(query)
        drift += 1
        rows.append(_common(f"INT-D{drift:02d}", "intent", "test", "ai_assisted_multi_turn",
                            {"query": query, "expect_intent": expect, "kind": "drift",
                             "history": "\n".join(turns[:-1]) + "\n", "turns": turns}))
    boundary = 0
    for query in BOUNDARY_QUESTIONS + BOUNDARY_SHORT:
        assert query not in used, f"边界问句重复:{query}"
        used.add(query)
        boundary += 1
        rows.append(_common(f"INT-B{boundary:03d}", "intent", "test", "ai_assisted_boundary",
                            {"query": query, "expect_intent": None, "kind": "boundary"}))
    return rows


