def _section_of(sections) -> str:
    if not sections:
        return ""
    first = sections[0]
    return first.split(" / ")[-1] if " / " in first else first


def _anchor_queries(query: str, variant: int) -> str:
    return RAG_PREFIXES[variant] + query + (RAG_SUFFIXES[variant] if variant else "")


def rag_rows() -> list[dict]:
    """每个锚点生成「原句」和带逗号的自然改写两个问法;盲测集每桶 60 题。

    改写必须保留在线检索的「按逗号拆子句」能力:跨文档题整句只有一个分句时,
    检索只按整句召回,标准答案里的两段证据里总有一段排不进前五。
    """
    rows = []
    seen = Counter()
    for bucket, tag, sections, points, query in RAG_ANCHORS:
        seen[tag] += 1
        for variant in range(2):
            suffix = "" if seen[tag] == 1 else f"-{seen[tag]}"
            if variant:
                suffix += "-B"
            q = (query if variant == 0 else
                 f"麻烦说明一下,{query}")
            sid = f"RAG-B-{BUCKET_CODE[bucket]}-{tag}{suffix}"
            if bucket == "D_absent":
                extra = {"query": q, "should_refuse": True}
                source = "kb_boundary"
            elif bucket == "E_multi":
                extra = {"query": q, "expect_sections_all": sections,
                         "expect_points": points, "should_refuse": False}
                source = "kb"
            else:
                extra = {"query": q, "expect_sections_all": [sections],
                         "expect_section": _section_of(sections),
                         "expect_points": points, "should_refuse": False}
                source = "kb"
            rows.append(_common(sid, "rag", "blind", source, {"bucket": bucket, **extra}))
    return rows


def all_rag_queries() -> set[str]:
    return {r["query"] for r in rag_rows()}


